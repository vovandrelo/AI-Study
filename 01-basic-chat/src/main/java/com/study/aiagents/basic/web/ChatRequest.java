package com.study.aiagents.basic.web;

/**
 * DTO для чата с системным промптом.
 * <p>
 * Используется двумя эндпоинтами:
 * <ul>
 *     <li>{@code POST /api/chat/with-system} — синхронный ответ;</li>
 *     <li>{@code POST /api/chat/stream}      — стриминг через Server-Sent Events.</li>
 * </ul>
 * <p>
 * <b>Что такое системный промпт.</b><br>
 * {@code system} задаёт «роль» / «характер» модели на весь диалог:
 * стиль ответа, формат, ограничения, доменные знания. Модель относится к нему
 * с более высоким приоритетом, чем к пользовательским сообщениям. Если оставить
 * {@code null} или пустую строку — будет отправлено только пользовательское сообщение
 * (поведение совпадёт с {@link SimpleChatRequest}).
 * <p>
 * <b>Примеры значений {@code system}:</b>
 * <ul>
 *     <li>{@code "Ты строгий технический рецензент. Отвечай по делу, без воды."}</li>
 *     <li>{@code "Ты — переводчик с русского на английский. Возвращай только перевод, без комментариев."}</li>
 *     <li>{@code "Отвечай ВСЕГДА в формате JSON со схемой {answer: string, confidence: number}."}</li>
 * </ul>
 *
 * @param system необязательный системный промпт (может быть {@code null} или пустым)
 * @param user   обязательное пользовательское сообщение
 */
public record ChatRequest(String system, String user) {
}
