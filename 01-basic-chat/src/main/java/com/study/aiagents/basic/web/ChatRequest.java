package com.study.aiagents.basic.web;

/**
 * Единый DTO запроса для всех трёх эндпоинтов чата.
 * <p>
 * Содержит ровно одно поле — {@code message} с пользовательским текстом.
 * <p>
 * <b>Почему здесь нет поля {@code system}.</b><br>
 * Системный промпт — это <i>серверная</i> настройка, а не пользовательский ввод.
 * Причины:
 * <ul>
 *     <li><b>Безопасность.</b> Если разрешить клиенту присылать свой system-промпт,
 *         любой пользователь сможет переопределить роль/ограничения ассистента
 *         (классический prompt injection через API). Сервер должен сам управлять
 *         характером модели.</li>
 *     <li><b>Качество.</b> Системный промпт — часть продукта. Его пишут, версионируют
 *         и A/B-тестят разработчики. Если он приходит снаружи, мы не можем
 *         гарантировать поведение системы.</li>
 *     <li><b>Разделение ответственности.</b> Клиент отвечает за «что спросить»,
 *         сервер — за «как ассистент должен себя вести».</li>
 * </ul>
 * Поэтому system-промпт хранится в {@code application.yml} (свойство {@code chat.system-prompt})
 * и инжектится в {@code ChatController} через {@code @Value}.
 * <p>
 * Используем Java {@code record} вместо обычного класса:
 * <ul>
 *     <li>иммутабельность из коробки;</li>
 *     <li>{@code equals/hashCode/toString} автоматически;</li>
 *     <li>Jackson 2.13+ корректно десериализует record по именам компонентов
 *         (имя в JSON должно совпадать с именем компонента — здесь {@code "message"}).</li>
 * </ul>
 *
 * @param message текст пользовательского сообщения; обязательное поле,
 *                валидация происходит в контроллере
 */
public record ChatRequest(String message) {
}
